const catalogues: Record<Locale, Partial<Record<MessageKey, string>>> = { en, te };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const message = catalogues[locale]?.[key] ?? catalogues[DEFAULT_LOCALE][key] ?? key;
  if (!vars) return message;
  return message.replace(/\{(\w+)\}/g, (_match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : `{${name}}`,
  );
}

export function createTranslator(locale: Locale) {
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
}
